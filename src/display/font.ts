export const GLYPH_HEIGHT = 7;
const SPACING = 1;

function glyph(ch: string): string[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

/** Width of a text in font dots (before scaling). */
export function textWidth(text: string): number {
  const chars = [...text];
  return chars.reduce((w, ch) => w + glyph(ch)[0].length, 0) + Math.max(0, chars.length - 1) * SPACING;
}

/** Lit cells of a text, as [column, row] in grid cells; each font dot covers scale x scale cells. */
export function textCells(text: string, col: number, row: number, scale = 1): [number, number][] {
  const cells: [number, number][] = [];
  let x = col;
  for (const ch of text) {
    const g = glyph(ch);
    g.forEach((line, fy) => {
      [...line].forEach((c, fx) => {
        if (c !== '#') return;
        for (let i = 0; i < scale; i++) for (let j = 0; j < scale; j++) cells.push([x + fx * scale + i, row + fy * scale + j]);
      });
    });
    x += (g[0].length + SPACING) * scale;
  }
  return cells;
}

/** The cells of each character separately, for effects that reveal text one character at a time. */
export function charCells(text: string, col: number, row: number, scale = 1): [number, number][][] {
  const out: [number, number][][] = [];
  let x = col;
  for (const ch of text) {
    const g = glyph(ch);
    out.push(textCells(ch, x, row, scale));
    x += (g[0].length + SPACING) * scale;
  }
  return out;
}
